"""
io_pod -- minimal Blender add-on for exporting EvoX vehicles.

The add-on writes the text SMF (`C3DModel`) mesh format plus a TRK stub, so a
custom model can be dropped into a POD with tools/podpack.py and loaded by the
game. Coordinates are converted from Blender metres to the game's inches.

Install: Edit > Preferences > Add-ons > Install, pick this file, enable
"EvoX POD (.SMF)". Export via File > Export > EvoX Model (.SMF).
"""

