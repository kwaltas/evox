def menu_func(self, context):
    self.layout.operator(EXPORT_OT_evox.bl_idname, text="EvoX Model (.SMF)")


def register():
    bpy.utils.register_class(EXPORT_OT_evox)
    bpy.types.TOPBAR_MT_file_export.append(menu_func)


def unregister():
    bpy.types.TOPBAR_MT_file_export.remove(menu_func)
    bpy.utils.unregister_class(EXPORT_OT_evox)


if __name__ == "__main__":
    register()
